// Builds single-file copies of the Edge Functions (shared helpers inlined) for deploying through the
// Supabase dashboard editor, when the CLI can't be used. Output: supabase/dashboard-deploy/<name>.ts
// Usage: node scripts/bundle-functions.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const FN = 'supabase/functions';
const OUT = 'supabase/dashboard-deploy';
mkdirSync(OUT, { recursive: true });

function inline(file, seen = new Set(), npm = new Set()) {
  if (seen.has(file)) return '';
  seen.add(file);
  const dir = file.slice(0, file.lastIndexOf('/'));
  const src = readFileSync(file, 'utf8');
  let body = '';
  for (const line of src.split(/\r?\n/)) {
    const local = line.match(/^import\s+.*from\s+'(\.\.?\/[^']+)';\s*$/);
    const ext = line.match(/^import\s+.*from\s+'((npm|jsr|https?):[^']+)';\s*$/);
    if (local) {
      const target = new URL(local[1], 'file:///' + dir + '/').pathname.replace(/^\/([A-Za-z]:)/, '$1');
      body += inline(target.replace(/^\//, ''), seen, npm);
    } else if (ext) npm.add(line.trim());
    else body += line + '\n';
  }
  return body;
}

for (const name of ['stripe-checkout', 'stripe-webhook', 'send-emails', 'public-forms']) {
  const npm = new Set();
  const body = inline(`${FN}/${name}/index.ts`, new Set(), npm);
  const header = `// GENERATED by scripts/bundle-functions.mjs from supabase/functions/${name} — paste into the Supabase dashboard editor.\n` +
    `// Edit the source files, not this copy.\n`;
  writeFileSync(`${OUT}/${name}.ts`, header + [...npm].join('\n') + '\n\n' + body.replace(/\n{3,}/g, '\n\n'));
  console.log(`${OUT}/${name}.ts`);
}
